"""Derive the budget file from a null collection: identical code, measured twice.

    python -m benchmarks.harness.calibrate DIR > benchmarks/budgets.toml

`DIR` is a paired collection where both sides are the same revision. Under that
null hypothesis every difference between the two sides is noise, so the spread of
the paired statistic over the runs is the spread a real comparison has to clear
before it means anything.

The runs are exchangeable, which is what makes a small collection carry a large
sample: with R repetitions there are 2R runs of the same code, and every way of
splitting them into two halves is another trial of the same statistic. `SPLITS`
orderings per split are taken, from a fixed seed, so the same collection yields
the same budgets every time it is calibrated.

    limit = max(class floor, 2 x paired null p99), rounded up to a whole percent

The deterministic budgets carry no measurement: a call count and an allocation
count may not increase at all, retained memory carries the 2% that absorbs
container resizing, and a scaling ratio carries the 15% ceiling of a
complexity-class test. They are emitted for whatever the collection measured, so
adding a workload cannot leave the file behind.

Run it on both hosts. A budget derived on a quiet workstation and applied to a
shared runner is how the first delivered gate came to fail a documentation-only
pull request.
"""

import argparse
import math
import random
import statistics
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from itertools import combinations
from pathlib import Path

from benchmarks.contracts import Metric, NoiseClass
from benchmarks.harness import (
    HarnessError,
    quantile,
    read_json,
    reduce,
    require_object,
    require_text,
)
from benchmarks.harness import budgets as budget_module
from benchmarks.harness.pairs import BASE, DETERMINISTIC_FILE, HEAD

USAGE = 'python -m benchmarks.harness.calibrate DIR'
SPLITS = 6
"""Orderings taken per split of the runs into two halves.

The trial count is `C(2R, R) x SPLITS` — 1512 for the five repetitions the gate
collects, which is the sample the delivered budgets were derived over.
"""

SEED = 20260902
QUANTILE = 0.99
MULTIPLIER = 2.0
PERCENT = 100.0

CLASS_BANDS: tuple[tuple[float, NoiseClass], ...] = (
    (0.03, NoiseClass.LOW),
    (0.06, NoiseClass.MEDIUM),
)

DETERMINISTIC_JUSTIFICATION: dict[str, str] = {
    budget_module.WORK: 'Python calls per operation; deterministic, so any increase is a real added call',
    Metric.ALLOCATIONS.value: 'blocks and bytes per operation; deterministic, so any increase is a real allocation',
    Metric.RETAINED.value: 'bytes still reachable; 2% absorbs container resizing and nothing more',
    Metric.SCALING.value: (
        'a ratio between two sizes, which cancels host noise; a complexity-class test, not a timing one'
    ),
}

DETERMINISTIC_LIMIT: dict[str, float] = {
    budget_module.WORK: 0.0,
    Metric.ALLOCATIONS.value: 0.0,
    Metric.RETAINED.value: budget_module.METRIC_CEILINGS[Metric.RETAINED.value],
    Metric.SCALING.value: budget_module.METRIC_CEILINGS[Metric.SCALING.value],
}

HEADER = """# Per-workload regression budgets, and the measurement each one rests on.
#
# Generated by `python -m benchmarks.harness.calibrate` over a paired null
# collection — identical code on both sides — and never edited by hand. A uniform
# threshold cannot be right: measured per-workload dispersion spans an order of
# magnitude, so one number is simultaneously too loose for the quiet workloads and
# too tight for the noisy ones. Each latency budget below is twice that workload's
# own measured paired null p99, floored by the band it falls in - 5% low, 8%
# medium, 15% high - and rounded up to a whole percent.
#
# Regenerate by the procedure in docs/performance/methodology.md. Never widen a
# budget to make a failing pull request green: benchmarks/harness/budgets.py
# refuses a latency limit under its class floor, and refuses to loosen any of the
# deterministic budgets at all."""


@dataclass(frozen=True, slots=True)
class Calibration:
    """One workload's measured null dispersion, and the budget it produces."""

    workload: str
    p99: float
    noise: NoiseClass
    limit: float
    trials: int


def noise_class(p99: float) -> NoiseClass:
    """The band a measured null p99 falls in, as `contracts.NoiseClass` defines them."""
    for ceiling, band in CLASS_BANDS:
        if p99 <= ceiling:
            return band
    return NoiseClass.HIGH


def derive(p99: float) -> tuple[NoiseClass, float]:
    """The noise class and budget a measured null p99 produces.

    Rounded up to a whole percent, because a budget is a stated tolerance and a
    reader should be able to hold it in mind. Rounding up never tightens what the
    measurement supports.

    Raises:
        HarnessError: `p99` is negative, which no dispersion is.

    Example:
        ```pycon
        >>> from benchmarks.harness.calibrate import derive
        >>> derive(0.0438)
        (<NoiseClass.MEDIUM: 'medium'>, 0.09)
        >>> derive(0.0192)
        (<NoiseClass.LOW: 'low'>, 0.05)

        ```
    """
    if p99 < 0.0:
        raise HarnessError(f'a null p99 of {p99!r}; a dispersion cannot be negative')
    band = noise_class(p99)
    derived = math.ceil(MULTIPLIER * p99 * PERCENT) / PERCENT
    return band, max(budget_module.CLASS_FLOORS[band], derived)


def _runs(dataset: Path) -> dict[str, list[float]]:
    """Every measured median per workload, both sides pooled, for the depin subjects only."""
    pooled: dict[str, list[float]] = {}
    for side in (BASE, HEAD):
        directory = dataset / side
        files = sorted(directory.glob('rep*.json'))
        if not files:
            raise HarnessError(f'{directory}: carries no rep<index>.json; a null collection measures both sides')
        for path in files:
            payload = read_json(path)
            stored = require_object(payload.get('aggregates'), f'{path}: aggregates')
            for name, aggregate in reduce.decode_all(stored, str(path)).items():
                workload = reduce.subject_of(name)
                if workload is None or not reduce.qualifies(aggregate):
                    continue
                pooled.setdefault(workload, []).append(aggregate.median)
    return pooled


def excursions(runs: Sequence[float], *, seed: int = SEED, orderings: int = SPLITS) -> list[float]:
    """The paired statistic over every split of `runs` into two halves.

    The sign is dropped. Under the null the statistic is symmetric, and what a
    budget has to clear is how far it travels rather than which way.

    Raises:
        HarnessError: fewer than four runs, which is too few to split into two
            halves that can carry a median, or `orderings` is below one.
    """
    if len(runs) < 4:
        raise HarnessError(f'{len(runs)} runs; a split into two halves needs at least four')
    if orderings < 1:
        raise HarnessError(f'{orderings} orderings; at least one is needed per split')
    for index, value in enumerate(runs):
        if not math.isfinite(value) or value <= 0.0:
            raise HarnessError(f'run[{index}] is {value!r}; a duration must be finite and positive')

    logged = [math.log(value) for value in runs]
    half = len(logged) // 2
    generator = random.Random(seed)
    measured: list[float] = []
    for left in combinations(range(len(logged)), half):
        chosen = set(left)
        right = [index for index in range(len(logged)) if index not in chosen]
        for _ in range(orderings):
            generator.shuffle(right)
            differences = [logged[after] - logged[before] for before, after in zip(left, right, strict=True)]
            measured.append(abs(math.expm1(statistics.median(differences))))
    return measured


def calibrate(dataset: Path) -> list[Calibration]:
    """Derive one latency budget per workload from a null collection.

    Raises:
        HarnessError: the collection carries no side directories, or a workload
            has too few qualifying runs to split.
    """
    calibrations: list[Calibration] = []
    for workload, runs in sorted(_runs(dataset).items()):
        measured = sorted(excursions(runs))
        p99 = quantile(measured, QUANTILE)
        band, limit = derive(p99)
        calibrations.append(Calibration(workload=workload, p99=p99, noise=band, limit=limit, trials=len(measured)))
    return calibrations


def _deterministic_names(dataset: Path) -> dict[str, list[str]]:
    """The workload names each deterministic metric measured, read off the head side."""
    payload = read_json(dataset / HEAD / DETERMINISTIC_FILE)
    named: dict[str, list[str]] = {}
    for metric in (budget_module.WORK, Metric.ALLOCATIONS.value, Metric.RETAINED.value, Metric.SCALING.value):
        section = require_object(payload.get(metric, {}), f'{dataset}: {metric}')
        named[metric] = sorted(section)
    return named


def _entry(workload: str, metric: str, limit: float, noise: NoiseClass, justification: str) -> str:
    return (
        '[[budget]]\n'
        f'workload = "{workload}"\n'
        f'metric = "{metric}"\n'
        f'limit = {limit:g}\n'
        f'noise = "{noise.value}"\n'
        f'justification = "{justification}"\n'
    )


def render(dataset: Path) -> str:
    """The complete budget file for `dataset`, latency and deterministic alike."""
    entries: list[str] = []
    for calibration in calibrate(dataset):
        entries.append(
            _entry(
                calibration.workload,
                Metric.LATENCY.value,
                calibration.limit,
                calibration.noise,
                f'paired null p99 {calibration.p99:.2%} over {calibration.trials} trials of identical code',
            )
        )
    for metric, names in sorted(_deterministic_names(dataset).items()):
        for workload in names:
            entries.append(
                _entry(
                    workload,
                    metric,
                    DETERMINISTIC_LIMIT[metric],
                    NoiseClass.LOW,
                    DETERMINISTIC_JUSTIFICATION[metric],
                )
            )
    return '\n'.join([HEADER, '', *entries]).rstrip('\n') + '\n'


def summary(calibrations: Sequence[Calibration]) -> str:
    """One line per workload, for reading a calibration without diffing a budget file."""
    width = max((len(calibration.workload) for calibration in calibrations), default=0)
    return ''.join(
        f'{calibration.workload:<{width}}  p99 {calibration.p99:>7.2%}  '
        f'{calibration.noise.value:<6}  budget {calibration.limit:>6.1%}\n'
        for calibration in calibrations
    )


def _arguments(argv: Sequence[str] | None) -> Mapping[str, object]:
    parser = argparse.ArgumentParser(prog='python -m benchmarks.harness.calibrate', description=USAGE)
    parser.add_argument('dataset', help='a paired collection in which both sides are the same revision')
    parser.add_argument('--summary', action='store_true', help='print the measured dispersion instead of the file')
    return dict(vars(parser.parse_args(argv)))


def main(argv: Sequence[str] | None = None) -> int:
    try:
        chosen = _arguments(argv)
        dataset = Path(require_text(chosen['dataset'], 'DIR'))
        text = summary(calibrate(dataset)) if chosen['summary'] else render(dataset)
        _ = sys.stdout.write(text)
    except HarnessError as error:
        _ = sys.stderr.write(f'{error}\n')
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
